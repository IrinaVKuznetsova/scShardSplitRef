# FUNCTION-3
# This function retains only gene_id, transcript_id, and gene_name attributes in the 9th column of the GTF file
# Recommended to retain only gene_id, transcript_id, and gene_name attributes.
# LINK: https://kb.10xgenomics.com/hc/en-us/articles/4707448154381-Common-mkref-formatting-errors-when-building-custom-reference-from-NCBI-UCSC-or-RefSeq-genomes


